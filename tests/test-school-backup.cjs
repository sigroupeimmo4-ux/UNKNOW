'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const backup=require('../school-backup.js');
assert.equal(backup.validDate('2026-10-30'),true);
assert.equal(backup.validDate('2026-02-29'),false);
assert.equal(backup.validDate('2024-02-29'),true);
assert.equal(backup.validDate('2026-02-31'),false);
assert.equal(backup.validTime('17:05'),true);
assert.equal(backup.validTime('27:05'),false);
const rows=[{id:'id1',date:'2026-10-30',type:'revision',title:'Relire les nombres',subject:'Mathématiques',start:'17:00',end:'18:00',repeat:'weekly',reminder:'1d',done:false,completedDates:['2026-10-30']}];
const encoded=JSON.stringify({format:'studybeam-local-v1',section:'calendar',items:rows});
const imported=backup.decode(encoded,'calendar');
assert.equal(imported.length,1);
assert.deepEqual(imported[0].completedDates,['2026-10-30']);
assert.equal(imported[0].repeat,'weekly');
assert.throws(()=>backup.decode(encoded,'grades'),/ne correspond/);
assert.throws(()=>backup.decode('{','calendar'),/illisible/);
assert.throws(()=>backup.decode(JSON.stringify({format:'studybeam-local-v1',section:'calendar',items:[{...rows[0],date:'2026-02-31'}]}),'calendar'),/Date invalide/);
assert.throws(()=>backup.decode(JSON.stringify({format:'studybeam-local-v1',section:'calendar',items:[rows[0],rows[0]]}),'calendar'),/dupliqu/);
assert.throws(()=>backup.decode(JSON.stringify({format:'studybeam-local-v1',section:'calendar',items:[{...rows[0],start:'21:00',end:'17:00'}]}),'calendar'),/invalide/);
assert.throws(()=>backup.decode(JSON.stringify({format:'studybeam-local-v1',section:'calendar',items:[{...rows[0],completedDates:['not-a-day']}]}),'calendar'),/invalides/);
assert.throws(()=>backup.decode(JSON.stringify({format:'studybeam-local-v1',section:'calendar',items:new Array(1501).fill(rows[0])}),'calendar'),/1 500/);
const grades=[{id:'g1',date:'2026-10-30',subject:'Français',label:'Évaluation',score:14,max:20}];
assert.deepEqual(backup.decode(JSON.stringify({format:'studybeam-local-v1',section:'grades',items:grades}),'grades'),grades);
assert.throws(()=>backup.decode(JSON.stringify({format:'studybeam-local-v1',section:'grades',items:[{...grades[0],score:40}]}),'grades'),/invalide/);
assert.throws(()=>backup.decode(JSON.stringify({format:'studybeam-local-v1',section:'grades',items:[{...grades[0],max:0}]}),'grades'),/invalide/);
const app=fs.readFileSync('app.html','utf8'),generator=fs.readFileSync('scripts/build_navigation_pages.py','utf8');
assert(!app.includes('id="dragon"'));
assert(!app.includes('id="costume"'));
assert(!app.includes('beam-customizer.js'));
assert(!generator.includes("('app.html#dragon','Mon dragon'"));
assert(!fs.readFileSync('beam-global.js','utf8').includes("['Mon Beam','app.html#dragon']"));
assert(fs.readFileSync('calendrier.html','utf8').includes('./school-backup.js'));
assert(fs.readFileSync('mes-notes.html','utf8').includes('./school-backup.js'));
console.log('OK — safe calendar/grades import, calendar dates and retired dragon-route contract');
